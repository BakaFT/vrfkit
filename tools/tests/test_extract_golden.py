import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


REPO = Path(__file__).resolve().parents[2]
GENERATOR = REPO / "tools" / "extract_golden.py"
BRANCHES = [
    "++Ares-Core+release-12.10",
    "++Ares-Core+release-12.11",
    "++Ares-Core+release-13.00",
    "++Ares-Core+release-13.01",
    "++Ares-Core+release-13.02",
    "++Ares-Core+release-13.04",
]
# Carried by historical fixtures but deliberately NOT used: the generator
# drops these rows and recomputes them with tools/china_transform_oracle.py.
# China 13.02's fixture implementation zeroed two lanes; China 13.04, 13.05,
# 13.08 and 13.09 have no external fixture and remain oracle-backed if one is
# added.
CHINA = "++Ares-Core+release-china-13.02"
CHINA_1304 = "++Ares-Core+release-china-13.04"
CHINA_1305 = "++Ares-Core+release-china-13.05"
CHINA_1308 = "++Ares-Core+release-china-13.08"
CHINA_1309 = "++Ares-Core+release-china-13.09"
REGIONAL = (CHINA, CHINA_1304, CHINA_1305, CHINA_1308, CHINA_1309)
BOUNDARIES = [0, 1, 7, 8, 31, 32, 63, 64, 65, 287, 288]


def fixture(cases: list[tuple[str, int]]) -> str:
    rows = []
    for branch, bits in cases:
        hex_text = "00" * ((bits + 7) // 8)
        rows.append(f'new("{branch}", {bits}, "{hex_text}")')
    return (
        'private const string PayloadHex = "' + ("00" * 36) + '";\n'
        "private const uint ActorNetGuid = 2;\n"
        "var cases = new[] {\n    " + ",\n    ".join(rows) + "\n};\n"
    )


def payload_of(line: str) -> str:
    """The expected-output hex from a generated `("branch", bits, "hex"),` row."""
    return line.rsplit('"', 2)[1]


class GoldenOracleContractTests(unittest.TestCase):
    def run_generator(self, cases, previous_output=""):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            source = root / "fixture.cs"
            output = root / "golden_vectors.rs"
            source.write_text(fixture(cases), encoding="utf-8")
            if previous_output:
                output.write_text(previous_output, encoding="utf-8")
            result = subprocess.run(
                [sys.executable, str(GENERATOR), str(source), str(output)],
                capture_output=True,
                text=True,
                encoding="utf-8",
                check=False,
            )
            content = output.read_text(encoding="utf-8") if output.exists() else None
            return result, content

    @staticmethod
    def fixture_cases():
        return [(branch, bits) for branch in BRANCHES for bits in BOUNDARIES]

    @classmethod
    def fixture_with_superseded_cases(cls):
        return (
            cls.fixture_cases()
            + [(branch, bits) for branch in REGIONAL for bits in BOUNDARIES]
        )

    def rows_for(self, output, branch):
        return [line for line in output.splitlines() if f'("{branch}"' in line]

    def test_exact_eleven_build_by_eleven_boundary_oracle_succeeds(self):
        result, output = self.run_generator(self.fixture_cases())
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("121 vectors across 11 builds", output)

    def test_non_66_fixture_is_rejected_without_replacing_previous_output(self):
        cases = self.fixture_cases()
        cases.remove((BRANCHES[-1], 288))
        result, output = self.run_generator(cases, previous_output="previous oracle\n")
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(output, "previous oracle\n")
        self.assertIn("66", result.stderr)

    def test_each_promised_build_must_have_the_full_boundary_set(self):
        cases = self.fixture_cases()
        cases[-1] = (BRANCHES[0], cases[-1][1])
        result, _ = self.run_generator(cases)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn(BRANCHES[-1], result.stderr)

    def test_duplicate_boundary_cannot_replace_a_missing_boundary(self):
        cases = self.fixture_cases()
        cases[-1] = (BRANCHES[-1], 287)
        result, _ = self.run_generator(cases)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("288", result.stderr)

    def test_a_fixture_without_the_superseded_rows_is_accepted(self):
        # Current global fixtures omit all five regional branches. Their
        # vectors are still generated by the independent oracle.
        result, output = self.run_generator(self.fixture_cases())
        self.assertEqual(result.returncode, 0, result.stderr)
        for branch in REGIONAL:
            self.assertEqual(len(self.rows_for(output, branch)), len(BOUNDARIES))

    def test_china_rows_come_from_the_oracle_not_the_fixture(self):
        # Every fixture row here is all-zero hex. The six lifted builds must
        # emit exactly that; all five regional builds must not, because their
        # rows are recomputed from the payload rather than copied.
        result, output = self.run_generator(self.fixture_with_superseded_cases())
        self.assertEqual(result.returncode, 0, result.stderr)

        for branch in REGIONAL:
            china_rows = self.rows_for(output, branch)
            self.assertEqual(len(china_rows), len(BOUNDARIES))

            # Zero bits is empty. Check every wider vector; one tail bit can
            # legitimately stay clear depending on the regional constants.
            recomputed = [
                payload_of(line)
                for line, bits in zip(china_rows, BOUNDARIES)
                if bits > 1
            ]
            self.assertTrue(recomputed)
            self.assertTrue(
                all(set(hex_text) != {"0"} for hex_text in recomputed),
                f"{branch} rows still look like the all-zero fixture: {recomputed}",
            )

        lifted = [payload_of(line) for line in self.rows_for(output, BRANCHES[0])]
        self.assertTrue(
            all(set(hex_text) <= {"0"} for hex_text in lifted),
            "a lifted build stopped matching its fixture rows",
        )


if __name__ == "__main__":
    unittest.main()
